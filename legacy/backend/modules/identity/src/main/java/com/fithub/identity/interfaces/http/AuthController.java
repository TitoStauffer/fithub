package com.fithub.identity.interfaces.http;

import com.fithub.identity.application.usecase.AuthenticateUserUseCase;
import com.fithub.identity.application.usecase.RegisterUserUseCase;
import com.fithub.identity.application.usecase.ValidateTokenUseCase;
import com.fithub.identity.domain.aggregate.User;
import com.fithub.identity.domain.repository.UserRepository;
import com.fithub.identity.infrastructure.security.JwtTokenProvider;
import com.fithub.identity.interfaces.dto.*;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.validation.BindingResult;
import org.springframework.web.bind.MethodArgumentNotValidException;
import org.springframework.web.bind.annotation.*;

import jakarta.validation.Valid;
import java.util.Optional;
import java.util.stream.Collectors;

/**
 * Controller HTTP para autenticação.
 * Endpoints:
 * - POST /auth/register → UC-ID-001
 * - POST /auth/login    → UC-ID-002
 * - POST /auth/validate → UC-ID-003
 *
 * Segurança: Rate limiting em /auth/register e /auth/login
 * Validação: @Valid em DTOs com @NotBlank, @Email, etc
 * Mensagens: Genéricas para evitar user enumeration
 *
 * Swagger docs auto-generated by springdoc-openapi
 */
@RestController
@RequestMapping("/auth")
public class AuthController {
    private static final Logger logger = LoggerFactory.getLogger(AuthController.class);
    private final RegisterUserUseCase registerUserUseCase;
    private final AuthenticateUserUseCase authenticateUserUseCase;
    private final ValidateTokenUseCase validateTokenUseCase;
    private final JwtTokenProvider jwtTokenProvider;
    private final UserRepository userRepository;

    public AuthController(RegisterUserUseCase registerUserUseCase,
                         AuthenticateUserUseCase authenticateUserUseCase,
                         ValidateTokenUseCase validateTokenUseCase,
                         JwtTokenProvider jwtTokenProvider,
                         UserRepository userRepository) {
        this.registerUserUseCase = registerUserUseCase;
        this.authenticateUserUseCase = authenticateUserUseCase;
        this.validateTokenUseCase = validateTokenUseCase;
        this.jwtTokenProvider = jwtTokenProvider;
        this.userRepository = userRepository;
    }

    /**
     * UC-ID-001: Registra novo usuário
     * POST /auth/register
     */
    @PostMapping("/register")
    public ResponseEntity<AuthResponse> register(@Valid @RequestBody RegisterUserRequest request) {
        try {
            RegisterUserUseCase.RegisterUserRequest useCaseRequest =
                new RegisterUserUseCase.RegisterUserRequest(
                    request.getEmail(),
                    request.getPassword(),
                    request.getRole(),
                    request.getName()
                );

            RegisterUserUseCase.RegisterUserResponse response = registerUserUseCase.execute(useCaseRequest);

            AuthResponse authResponse = new AuthResponse(
                response.getUserId(),
                response.getEmail(),
                response.getRole(),
                response.getName(),
                null,
                null
            );

            return ResponseEntity.status(HttpStatus.CREATED).body(authResponse);

        } catch (IllegalArgumentException e) {
            if (e.getMessage().contains("already registered")) {
                logger.warn("Registration failed: Email already registered");
                return ResponseEntity.status(HttpStatus.CONFLICT)
                    .body(new AuthResponse(null, request.getEmail(), null, null, null, null));
            }
            logger.warn("Registration failed: Invalid input - {}", e.getMessage());
            return ResponseEntity.badRequest().build();
        }
    }

    /**
     * UC-ID-002: Autentica usuário e retorna JWT
     * POST /auth/login
     */
    @PostMapping("/login")
    public ResponseEntity<AuthResponse> login(@Valid @RequestBody LoginRequest request) {
        try {
            AuthenticateUserUseCase.AuthenticateUserRequest useCaseRequest =
                new AuthenticateUserUseCase.AuthenticateUserRequest(request.getEmail(), request.getPassword());

            AuthenticateUserUseCase.AuthenticateUserResponse response =
                authenticateUserUseCase.execute(useCaseRequest);

            AuthResponse authResponse = new AuthResponse(
                null,
                request.getEmail(),
                response.getRole(),
                null,
                response.getAccessToken(),
                response.getRefreshToken()
            );

            return ResponseEntity.ok(authResponse);

        } catch (AuthenticateUserUseCase.AuthenticationFailedException e) {
            // Mensagem genérica (não revela se email existe ou password é errada)
            logger.warn("Login attempt failed for email: {}", request.getEmail());
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED)
                .body(new AuthResponse(null, null, null, null, null, null));
        } catch (Exception e) {
            logger.error("Unexpected error during login", e);
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
        }
    }

    /**
     * UC-ID-003: Valida token JWT
     * POST /auth/validate
     */
    @PostMapping("/validate")
    public ResponseEntity<ValidateTokenResponse> validateToken(
        @RequestHeader("Authorization") String authHeader) {
        try {
            String token = authHeader.replace("Bearer ", "");
            ValidateTokenUseCase.ValidateTokenResponse response = validateTokenUseCase.execute(token);

            return ResponseEntity.ok(new ValidateTokenResponse(response.getUserId(), response.getRole()));

        } catch (IllegalArgumentException e) {
            logger.debug("Token validation failed: {}", e.getMessage());
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
        }
    }

    /**
     * POST /auth/refresh
     * Renova o access token usando refresh token
     * Requer: refresh token no body da requisição
     */
    @PostMapping("/refresh")
    public ResponseEntity<AuthResponse> refreshToken(@Valid @RequestBody RefreshTokenRequest request) {
        try {
            // Validar o refresh token
            if (!jwtTokenProvider.validateToken(request.getRefreshToken())) {
                logger.warn("Invalid refresh token");
                return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
            }

            // Extrair userId do refresh token
            java.util.UUID userId = jwtTokenProvider.extractUserId(request.getRefreshToken());

            // Validar que o token é realmente um refresh token
            String tokenType = jwtTokenProvider.extractTokenType(request.getRefreshToken());
            if (!"refresh".equals(tokenType)) {
                logger.warn("Token is not a refresh token: {}", tokenType);
                return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
            }

            // Buscar usuário no banco
            Optional<User> userOptional = userRepository.findById(userId);
            if (userOptional.isEmpty()) {
                logger.warn("User not found for refresh: {}", userId);
                return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
            }

            User user = userOptional.get();

            // Gerar novo access token
            String newAccessToken = jwtTokenProvider.generateAccessToken(userId, user.getRole());
            String newRefreshToken = jwtTokenProvider.generateRefreshToken(userId);

            logger.info("Token refreshed for user: {}", userId);

            AuthResponse response = new AuthResponse(
                user.getId().toString(),
                user.getEmail().getValue(),
                user.getRole().name(),
                user.getName(),
                newAccessToken,
                newRefreshToken
            );

            return ResponseEntity.ok(response);

        } catch (IllegalArgumentException e) {
            logger.debug("Token validation failed during refresh: {}", e.getMessage());
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
        } catch (Exception e) {
            logger.error("Error refreshing token", e);
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
        }
    }

    /**
     * GET /auth/me
     * Retorna dados completos do usuário autenticado
     * Requer: Authorization header com JWT token válido
     */
    @GetMapping("/me")
    public ResponseEntity<UserProfileResponse> getCurrentUser(
        @RequestHeader("Authorization") String authHeader) {
        try {
            String token = authHeader.replace("Bearer ", "");
            java.util.UUID userId = jwtTokenProvider.extractUserId(token);

            Optional<User> userOptional = userRepository.findById(userId);
            if (userOptional.isEmpty()) {
                logger.warn("User not found: {}", userId);
                return ResponseEntity.status(HttpStatus.NOT_FOUND).build();
            }

            User user = userOptional.get();
            UserProfileResponse response = new UserProfileResponse(
                userId.toString(),
                user.getEmail().getValue(),
                user.getName(),
                user.getRole().name()
            );

            return ResponseEntity.ok(response);

        } catch (IllegalArgumentException e) {
            logger.debug("Token validation failed: {}", e.getMessage());
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
        } catch (Exception e) {
            logger.error("Error fetching user profile", e);
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
        }
    }

    /**
     * Exception handler: validação de entrada falha (DTOs com @Valid)
     */
    @ExceptionHandler(MethodArgumentNotValidException.class)
    public ResponseEntity<ErrorResponse> handleValidationExceptions(
        MethodArgumentNotValidException e) {

        String errors = e.getBindingResult().getFieldErrors().stream()
            .map(fe -> fe.getField() + ": " + fe.getDefaultMessage())
            .collect(Collectors.joining(", "));

        logger.warn("Validation error: {}", errors);
        return ResponseEntity.badRequest()
            .body(new ErrorResponse("Validation error: " + errors, "VALIDATION_ERROR"));
    }

    /**
     * Exception handler: erros não previstos
     */
    @ExceptionHandler(Exception.class)
    public ResponseEntity<ErrorResponse> handleGenericException(Exception e) {
        logger.error("Unhandled exception in auth controller", e);
        return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR)
            .body(new ErrorResponse("An error occurred. Please try again later.", "INTERNAL_ERROR"));
    }
}
