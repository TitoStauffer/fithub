package com.fithub.training.interfaces.http;

import com.fithub.training.application.usecase.CreateWorkoutPlanUseCase;
import com.fithub.training.application.usecase.RecordWorkoutExecutionUseCase;
import com.fithub.training.infrastructure.persistence.WorkoutExecutionEntity;
import com.fithub.training.infrastructure.persistence.WorkoutExecutionJpaRepositorySpringData;
import com.fithub.training.interfaces.dto.WorkoutExecutionRequest;
import com.fithub.training.interfaces.dto.WorkoutExecutionResponse;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import jakarta.validation.Valid;
import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Swagger docs auto-generated by springdoc-openapi
 */
@RestController
@RequestMapping("/training")
public class TrainingController {
    private static final Logger logger = LoggerFactory.getLogger(TrainingController.class);
    private final CreateWorkoutPlanUseCase createWorkoutPlanUseCase;
    private final RecordWorkoutExecutionUseCase recordWorkoutExecutionUseCase;
    private final WorkoutExecutionJpaRepositorySpringData workoutExecutionRepository;

    public TrainingController(CreateWorkoutPlanUseCase createWorkoutPlanUseCase,
                            RecordWorkoutExecutionUseCase recordWorkoutExecutionUseCase,
                            WorkoutExecutionJpaRepositorySpringData workoutExecutionRepository) {
        this.createWorkoutPlanUseCase = createWorkoutPlanUseCase;
        this.recordWorkoutExecutionUseCase = recordWorkoutExecutionUseCase;
        this.workoutExecutionRepository = workoutExecutionRepository;
    }

    @PostMapping("/plans")
    public ResponseEntity<CreateWorkoutPlanUseCase.CreateWorkoutPlanResponse> createPlan(
        @RequestBody CreateWorkoutPlanUseCase.CreateWorkoutPlanRequest request) {
        CreateWorkoutPlanUseCase.CreateWorkoutPlanResponse response = createWorkoutPlanUseCase.execute(request);
        return ResponseEntity.status(HttpStatus.CREATED).body(response);
    }

    @PostMapping("/executions")
    public ResponseEntity<RecordWorkoutExecutionUseCase.RecordExecutionResponse> recordExecution(
        @RequestBody RecordWorkoutExecutionUseCase.RecordExecutionRequest request) {
        RecordWorkoutExecutionUseCase.RecordExecutionResponse response = recordWorkoutExecutionUseCase.execute(request);
        return ResponseEntity.status(HttpStatus.CREATED).body(response);
    }

    /**
     * POST /patients/{patientId}/training/executions/record
     * Registra uma execução de treino com validação
     * Path variable seguro: patientId não fica exposto em query strings
     */
    @PostMapping("/patients/{patientId}/training/executions/record")
    public ResponseEntity<WorkoutExecutionResponse> recordWorkoutExecution(
        @PathVariable UUID patientId,
        @RequestHeader("Authorization") String authHeader,
        @Valid @RequestBody WorkoutExecutionRequest request) {
        try {
            String token = authHeader.replace("Bearer ", "");
            UUID executionId = UUID.randomUUID();

            // TODO: Validar se o profissional logado tem acesso a este paciente
            WorkoutExecutionEntity entity = new WorkoutExecutionEntity(
                executionId,
                patientId,
                request.getExerciseName(),
                request.getSets(),
                request.getReps(),
                request.getWeight(),
                request.getFeeling(),
                request.getStatus(),
                LocalDateTime.now()
            );

            workoutExecutionRepository.save(entity);
            logger.info("Workout execution recorded: {}", executionId);

            return ResponseEntity.status(HttpStatus.CREATED)
                .body(new WorkoutExecutionResponse(
                    executionId.toString(),
                    request.getExerciseName(),
                    request.getSets(),
                    request.getReps(),
                    request.getWeight(),
                    request.getFeeling(),
                    request.getStatus()
                ));

        } catch (IllegalArgumentException e) {
            logger.warn("Invalid workout execution: {}", e.getMessage());
            return ResponseEntity.badRequest().build();
        } catch (Exception e) {
            logger.error("Error recording workout execution", e);
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
        }
    }

    /**
     * GET /patients/{patientId}/training/executions
     * Lista todas as execuções de treino de um paciente
     */
    @GetMapping("/patients/{patientId}/training/executions")
    public ResponseEntity<java.util.List<WorkoutExecutionResponse>> getPatientWorkouts(
        @PathVariable UUID patientId,
        @RequestHeader("Authorization") String authHeader) {
        try {
            java.util.List<WorkoutExecutionEntity> executions = workoutExecutionRepository.findByPatientId(patientId);
            java.util.List<WorkoutExecutionResponse> responses = executions.stream()
                .map(e -> new WorkoutExecutionResponse(
                    e.getId().toString(),
                    e.getExerciseName(),
                    e.getSets(),
                    e.getReps(),
                    e.getWeight(),
                    e.getFeeling(),
                    e.getStatus()
                ))
                .toList();

            return ResponseEntity.ok(responses);
        } catch (Exception e) {
            logger.error("Error fetching patient workouts", e);
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
        }
    }

    @ExceptionHandler(Exception.class)
    public ResponseEntity<?> handleException(Exception e) {
        logger.error("Unhandled exception in training controller", e);
        return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
    }
}
