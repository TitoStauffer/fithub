package com.fithub.nutrition.interfaces.http;

import com.fithub.nutrition.application.usecase.CreateDietPlanUseCase;
import com.fithub.nutrition.infrastructure.persistence.NutritionMealExecutionEntity;
import com.fithub.nutrition.infrastructure.persistence.NutritionMealExecutionJpaRepository;
import com.fithub.nutrition.interfaces.dto.MealExecutionRequest;
import com.fithub.nutrition.interfaces.dto.MealExecutionResponse;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import jakarta.validation.Valid;
import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Swagger docs auto-generated by springdoc-openapi
 */
@RestController
@RequestMapping("/nutrition")
public class NutritionController {
    private static final Logger logger = LoggerFactory.getLogger(NutritionController.class);
    private final CreateDietPlanUseCase createDietPlanUseCase;
    private final NutritionMealExecutionJpaRepository mealExecutionRepository;

    public NutritionController(CreateDietPlanUseCase createDietPlanUseCase,
                             NutritionMealExecutionJpaRepository mealExecutionRepository) {
        this.createDietPlanUseCase = createDietPlanUseCase;
        this.mealExecutionRepository = mealExecutionRepository;
    }

    @PostMapping("/plans")
    public ResponseEntity<CreateDietPlanUseCase.CreateDietPlanResponse> createPlan(
        @RequestBody CreateDietPlanUseCase.CreateDietPlanRequest request) {
        CreateDietPlanUseCase.CreateDietPlanResponse response = createDietPlanUseCase.execute(request);
        return ResponseEntity.status(HttpStatus.CREATED).body(response);
    }

    /**
     * POST /patients/{patientId}/nutrition/executions/record
     * Registra uma execução de refeição com validação
     * Path variable seguro: patientId não fica exposto em query strings
     */
    @PostMapping("/patients/{patientId}/nutrition/executions/record")
    public ResponseEntity<MealExecutionResponse> recordMealExecution(
        @PathVariable UUID patientId,
        @RequestHeader("Authorization") String authHeader,
        @Valid @RequestBody MealExecutionRequest request) {
        try {
            String token = authHeader.replace("Bearer ", "");
            UUID executionId = UUID.randomUUID();
            Integer calories = (int) ((request.getProtein() * 4) + (request.getCarbs() * 4) + (request.getFat() * 9));

            // TODO: Validar se o profissional logado tem acesso a este paciente
            NutritionMealExecutionEntity entity = new NutritionMealExecutionEntity(
                executionId,
                patientId,
                request.getMealName(),
                request.getProtein(),
                request.getCarbs(),
                request.getFat(),
                calories,
                request.getCompleted(),
                LocalDateTime.now()
            );

            mealExecutionRepository.save(entity);
            logger.info("Meal execution recorded: {}", executionId);

            return ResponseEntity.status(HttpStatus.CREATED)
                .body(new MealExecutionResponse(
                    executionId.toString(),
                    request.getMealName(),
                    request.getProtein(),
                    request.getCarbs(),
                    request.getFat(),
                    calories,
                    request.getCompleted()
                ));

        } catch (IllegalArgumentException e) {
            logger.warn("Invalid meal execution: {}", e.getMessage());
            return ResponseEntity.badRequest().build();
        } catch (Exception e) {
            logger.error("Error recording meal execution", e);
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
        }
    }

    /**
     * GET /patients/{patientId}/nutrition/executions
     * Lista todas as execuções de refeição de um paciente
     */
    @GetMapping("/patients/{patientId}/nutrition/executions")
    public ResponseEntity<java.util.List<MealExecutionResponse>> getPatientMeals(
        @PathVariable UUID patientId,
        @RequestHeader("Authorization") String authHeader) {
        try {
            java.util.List<NutritionMealExecutionEntity> executions = mealExecutionRepository.findByPatientId(patientId);
            java.util.List<MealExecutionResponse> responses = executions.stream()
                .map(m -> new MealExecutionResponse(
                    m.getId().toString(),
                    m.getMealName(),
                    m.getProtein(),
                    m.getCarbs(),
                    m.getFat(),
                    m.getCalories(),
                    m.getCompleted()
                ))
                .toList();

            return ResponseEntity.ok(responses);
        } catch (Exception e) {
            logger.error("Error fetching patient meals", e);
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
        }
    }

    @ExceptionHandler(Exception.class)
    public ResponseEntity<?> handleException(Exception e) {
        logger.error("Unhandled exception in nutrition controller", e);
        return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
    }
}
