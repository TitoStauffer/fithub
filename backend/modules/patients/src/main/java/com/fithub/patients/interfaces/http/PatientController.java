package com.fithub.patients.interfaces.http;

import com.fithub.patients.application.usecase.CreatePatientUseCase;
import com.fithub.patients.application.usecase.UpdateBiometricsUseCase;
import com.fithub.patients.domain.aggregate.Patient;
import com.fithub.patients.domain.repository.PatientRepository;
import com.fithub.patients.interfaces.dto.PatientListResponse;
import com.fithub.identity.infrastructure.security.JwtTokenProvider;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.UUID;

/**
 * Controller HTTP para gerenciar pacientes.
 * Endpoints:
 * - GET /patients → Lista pacientes do profissional logado
 * - POST /patients → UC-PAT-001
 * - PUT /patients/{id}/biometrics → UC-PAT-002
 *
 * Swagger docs auto-generated by springdoc-openapi
 */
@RestController
@RequestMapping("/patients")
public class PatientController {
    private static final Logger logger = LoggerFactory.getLogger(PatientController.class);
    private final CreatePatientUseCase createPatientUseCase;
    private final UpdateBiometricsUseCase updateBiometricsUseCase;
    private final PatientRepository patientRepository;
    private final JwtTokenProvider jwtTokenProvider;

    public PatientController(CreatePatientUseCase createPatientUseCase,
                            UpdateBiometricsUseCase updateBiometricsUseCase,
                            PatientRepository patientRepository,
                            JwtTokenProvider jwtTokenProvider) {
        this.createPatientUseCase = createPatientUseCase;
        this.updateBiometricsUseCase = updateBiometricsUseCase;
        this.patientRepository = patientRepository;
        this.jwtTokenProvider = jwtTokenProvider;
    }

    /**
     * GET /patients
     * Lista todos os pacientes do profissional autenticado
     */
    @GetMapping
    public ResponseEntity<List<PatientListResponse>> listPatients(
        @RequestHeader("Authorization") String authHeader) {
        try {
            String token = authHeader.replace("Bearer ", "");
            UUID professionalUserId = jwtTokenProvider.extractUserId(token);

            List<Patient> patients = patientRepository.findByProfessionalUserId(professionalUserId);
            List<PatientListResponse> responses = patients.stream()
                .map(p -> new PatientListResponse(
                    p.getId().toString(),
                    p.getName(),
                    p.getBiometrics().getWeight(),
                    p.getBiometrics().getAge(),
                    p.getBiometrics().getHeight(),
                    p.getBiometrics().getImc(),
                    p.getStatus().name()
                ))
                .toList();

            return ResponseEntity.ok(responses);

        } catch (IllegalArgumentException e) {
            logger.debug("Token validation failed: {}", e.getMessage());
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
        } catch (Exception e) {
            logger.error("Error fetching patients", e);
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
        }
    }

    @PostMapping
    public ResponseEntity<CreatePatientUseCase.CreatePatientResponse> createPatient(
        @RequestBody CreatePatientUseCase.CreatePatientRequest request) {
        try {
            CreatePatientUseCase.CreatePatientResponse response = createPatientUseCase.execute(request);
            return ResponseEntity.status(HttpStatus.CREATED).body(response);
        } catch (IllegalArgumentException e) {
            logger.warn("Failed to create patient: {}", e.getMessage());
            return ResponseEntity.badRequest().build();
        }
    }

    @PutMapping("/{id}/biometrics")
    public ResponseEntity<UpdateBiometricsUseCase.UpdateBiometricsResponse> updateBiometrics(
        @PathVariable String id,
        @RequestBody UpdateBiometricsUseCase.UpdateBiometricsRequest request) {
        try {
            request.setPatientId(id);
            UpdateBiometricsUseCase.UpdateBiometricsResponse response = updateBiometricsUseCase.execute(request);
            return ResponseEntity.ok(response);
        } catch (IllegalArgumentException e) {
            logger.warn("Failed to update biometrics: {}", e.getMessage());
            return ResponseEntity.badRequest().build();
        }
    }

    @ExceptionHandler(Exception.class)
    public ResponseEntity<?> handleException(Exception e) {
        logger.error("Unhandled exception in patient controller", e);
        return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).build();
    }
}
